import { useState } from 'react';
import { questionsAPI } from '@/entities/dd-type';
import toast from 'react-hot-toast';

export const useQuestions = (selectedDdType, onRefresh) => {
  const [editingQuestion, setEditingQuestion] = useState(null);
  const [showAdvancedOptions, setShowAdvancedOptions] = useState(false);

  const createQuestion = (sectionId) => {
    const section = selectedDdType?.sections?.find(s => s.id === sectionId);
    const questionsInSection = section?.questions || [];

    setEditingQuestion({
      section_id: sectionId,
      question_text: '',
      order_index: questionsInSection.length,
      context_prompt: ''
      // question_code will be auto-generated by backend
    });
  };

  const editQuestion = (question) => {
    setEditingQuestion({ ...question });
  };

  const saveQuestion = async () => {
    // Only validate question_text (question_code is auto-generated for new questions)
    if (!editingQuestion.question_text) {
      toast.error('Question text is required');
      return false;
    }

    try {
      if (editingQuestion.id) {
        await questionsAPI.updateQuestion(editingQuestion.id, editingQuestion);
        toast.success('Question updated successfully');
      } else {
        // Destructure to exclude section_id and id from the request body
        // section_id is passed as URL parameter, not in body
        const { section_id, id, ...questionData } = editingQuestion;
        await questionsAPI.createQuestion(selectedDdType.code, section_id, questionData);
        toast.success('Question created successfully');
      }

      setEditingQuestion(null);
      setShowAdvancedOptions(false);
      await onRefresh();
      return true;
    } catch (error) {
      // Handle validation errors from backend
      let errorMessage = 'Failed to save question';
      if (error.response?.data?.detail) {
        if (Array.isArray(error.response.data.detail)) {
          // FastAPI validation error format
          errorMessage = error.response.data.detail.map(e => e.msg).join(', ');
        } else if (typeof error.response.data.detail === 'string') {
          errorMessage = error.response.data.detail;
        }
      }
      toast.error(errorMessage);
      return false;
    }
  };

  const deleteQuestion = async (questionId) => {
    if (!window.confirm('Are you sure you want to delete this question?')) {
      return false;
    }

    try {
      await questionsAPI.deleteQuestion(questionId);
      toast.success('Question deleted successfully');
      await onRefresh();
      return true;
    } catch (error) {
      toast.error(error.response?.data?.detail || 'Failed to delete question');
      return false;
    }
  };

  const reorderQuestion = async (questionId, newOrder) => {
    try {
      await questionsAPI.reorderQuestion(questionId, newOrder);
      await onRefresh();
      return true;
    } catch (error) {
      toast.error('Failed to reorder question');
      return false;
    }
  };

  const cancelEdit = () => {
    setEditingQuestion(null);
    setShowAdvancedOptions(false);
  };

  return {
    editingQuestion,
    setEditingQuestion,
    showAdvancedOptions,
    setShowAdvancedOptions,
    createQuestion,
    editQuestion,
    saveQuestion,
    deleteQuestion,
    reorderQuestion,
    cancelEdit
  };
};
