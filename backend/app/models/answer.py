class AnswerStatus(str, enum.Enum):
    """
    Answer status tracking for AI processing and human review workflows.

    AI Processing Statuses:
    - COMPLETED: Answer successfully generated by AI
    - FAILED: Answer generation failed, requires retry

    Review Workflow Statuses:
    - DRAFT: Initial draft state, not yet reviewed
    - NEEDS_REVIEW: Answer requires human review
    - APPROVED: Answer approved by reviewer
    - REJECTED: Answer rejected by reviewer
    """

    # AI Processing statuses
    COMPLETED = "completed"
    FAILED = "failed"

    # Review workflow statuses
    DRAFT = "draft"
    NEEDS_REVIEW = "needs_review"
    APPROVED = "approved"
    REJECTED = "rejected"


class ErrorType(str, enum.Enum):
    """Categorized error types for better error handling and retry logic"""

    RATE_LIMIT = "rate_limit"  # API rate limit exceeded - retryable with backoff
    CONTEXT_OVERFLOW = "context_overflow"  # Context length exceeded - may need truncation
    API_ERROR = "api_error"  # General API error from OpenAI
    NETWORK_ERROR = "network_error"  # Network/connection issues - retryable
    VALIDATION_ERROR = "validation_error"  # Input validation error - not retryable
    TIMEOUT = "timeout"  # Request timeout - retryable
    UNKNOWN = "unknown"  # Unknown error type


class DDAnswer(SQLModel, table=True):
    __tablename__ = "dd_answers"
    __table_args__ = (
        # The dashboard counts the current answers of every session by status.
        Index("ix_dd_answers_session_current_status", "session_id", "is_current", "status"),
        Index("ix_dd_answers_execution_status", "execution_id", "status"),
        # At most one current answer per question of a run. Partial on SQLite
        # too, so the tests see the rule.
        Index(
            "ix_dd_answers_one_current",
            "execution_id",
            "question_id",
            unique=True,
            postgresql_where=text("is_current"),
            sqlite_where=text("is_current"),
        ),
        CheckConstraint("tokens_used >= 0", name="tokens_non_negative"),
    )

    # What the answer is: the answer of a run (execution_id) to a question.
    # Everything below down to the codes follows from these two, and is filled
    # in one place only, engine/answers.new_answer.
    id: int | None = Field(default=None, primary_key=True)
    execution_id: int = Field(foreign_key="dd_executions.id", ondelete="CASCADE")
    question_id: int = Field(foreign_key="dd_questions.id", index=True)

    # Copies of the run's session and DD type and of the question's section,
    # kept for the dashboard's indexes and the filters of the review page.
    session_id: int = Field(foreign_key="dd_sessions.id", ondelete="CASCADE")
    dd_type_id: int | None = Field(default=None, foreign_key="dd_types.id", index=True)
    section_id: int | None = Field(default=None, foreign_key="dd_sections.id", index=True)

    # The codes as they read when the question was answered: a copy at answer
    # time, which a later change of code does not reach.
    section_code: str = Field(max_length=50)
    question_code: str = Field(max_length=50)

    # Version control fields
    version: int = defaulted_field(1)
    is_current: bool = defaulted_field(True)
    status: AnswerStatus = defaulted_field(
        AnswerStatus.NEEDS_REVIEW,
        sa_type=enum_type(AnswerStatus, "answer_status", store_values=True),
    )
    edited_by: int | None = Field(default=None, foreign_key="users.id")
    edited_at: datetime | None = Field(default=None, sa_type=TIMESTAMP)

    # Answer content
    answer_text: str | None = Field(default=None, sa_type=Text)
    sources: Any | None = Field(default=None, sa_type=JSONType)  # documents and web references

    # Processing metadata
    tokens_used: int = defaulted_field(0)

    # The OpenAI response that produced this answer: keeps the context chain
    # right when a question is retried.
    response_id: str | None = Field(
        default=None,
        max_length=255,
        foreign_key="dd_responses.response_id",
        ondelete="SET NULL",
        index=True,
    )

    # Error tracking for robust retry logic
    retry_count: int = defaulted_field(0)
    error_type: ErrorType | None = Field(
        default=None, sa_type=enum_type(ErrorType, "error_type", store_values=True)
    )
    error_message: str | None = Field(default=None, sa_type=Text)
    last_error_at: datetime | None = Field(default=None, sa_type=TIMESTAMP)

    # Timestamps
    answered_at: datetime | None = Field(default=None, sa_type=TIMESTAMP)
    created_at: datetime = timestamp_field(nullable=False)
    updated_at: datetime = timestamp_field(updated=True, nullable=False)

    session: Optional["DDSession"] = Relationship(back_populates="answers")
    execution: Optional["DDExecution"] = Relationship(back_populates="answers")
    section: Optional["DDSection"] = Relationship(
        sa_relationship_kwargs={"foreign_keys": "DDAnswer.section_id"}
    )
    question: Optional["DDQuestion"] = Relationship(
        sa_relationship_kwargs={"foreign_keys": "DDAnswer.question_id"}
    )
    dd_type_obj: Optional["DDType"] = Relationship(
        sa_relationship_kwargs={"foreign_keys": "DDAnswer.dd_type_id"}
    )
    editor: Optional["User"] = Relationship(
        sa_relationship_kwargs={"foreign_keys": "DDAnswer.edited_by"}
    )
    response: Optional["DDResponse"] = Relationship(
        sa_relationship_kwargs={"foreign_keys": "DDAnswer.response_id"}
    )
    history: list["DDAnswerHistory"] = Relationship(
        back_populates="answer", sa_relationship_kwargs={"cascade": "all, delete-orphan"}
    )


def decode_sources(value: Any) -> Any:
    """Sources as stored (a dict or a list), or as some clients send them: a
    JSON string. A value that is neither is kept, wrapped, for the reader."""
    if value is None or isinstance(value, dict | list):
        return value
    if isinstance(value, str):
        try:
            parsed = json.loads(value)
        except (json.JSONDecodeError, ValueError):
            return {"value": value}
        return parsed if isinstance(parsed, dict | list) else {"value": parsed}
    return {"value": str(value)}


class AnswerUpdate(SQLModel):
    """A reviewer's edit."""

    answer_text: str
    edit_reason: str | None = None
    sources: dict[str, Any] | list[Any] | None = None

    @field_validator("sources", mode="before")
    @classmethod
    def _sources(cls, value: Any) -> Any:
        decoded = decode_sources(value)
        # Only real sources are stored: an unreadable value is dropped.
        return None if isinstance(decoded, dict) and set(decoded) == {"value"} else decoded


class AnswerResponse(SQLModel):
    id: int
    session_id: int
    execution_id: int | None
    dd_type_id: int | None
    dd_type_code: str | None = None
    section_code: str | None = None
    question_code: str | None = None
    answer_text: str | None
    sources: Any | None = None
    tokens_used: int = 0
    status: AnswerStatus

    # Versions
    version: int = 1
    is_current: bool = True
    edited_by: int | None = None
    edited_at: datetime | None = None
    is_edited: bool = False
    retry_count: int = 0
    answered_at: datetime | None
    created_at: datetime
    updated_at: datetime | None

    # Labels for the review page (services/answers.py)
    editor_name: str | None = None
    session_name: str | None = None
    section_name: str | None = None
    question_text: str | None = None
    validation_status: str | None = None
    total_validations: int = 0
    openai_message_ids: list[str] = []

    @field_validator("sources", mode="before")
    @classmethod
    def _sources(cls, value: Any) -> Any:
        return decode_sources(value)


class AnswerListResponse(SQLModel):
    answers: list[AnswerResponse]
    pagination: dict[str, Any]
    filters: dict[str, Any] | None = None
    stats: dict[str, Any] | None = None

    @classmethod
    def of(
        cls,
        answers: list[AnswerResponse],
        meta: PaginationMeta,
        filters: dict[str, Any],
        stats: dict[str, Any] | None = None,
    ) -> "AnswerListResponse":
        return cls(answers=answers, pagination=meta.model_dump(), filters=filters, stats=stats)
