"""The answering engine: answers the questions of one DD type of a session.

A run, started or resumed, goes through one loop (_run): question after
question, until the questions run out, the user pauses it, or the circuit
breaker opens. Its final status is decided in one place (_final_status).

Each question is one OpenAI call, with the engine's retries (engine/errors.py)
and outside any transaction, then one transaction that writes all it produced:
the raw response and its messages, the old answer set aside, the new answer and
the first version of its history. A failure between the two leaves the
question as it was.

The questions are not chained into one OpenAI conversation: each call carries
the text of the answers already written for the earlier questions
(compose_earlier_answers). Chaining sent every earlier search result again,
and a question cost 12 to 15 times the input it costs alone.

The run's execution is created and set in progress by the service
(services/processing.py), which hands its id over.
"""

