logger = logging.getLogger(__name__)

# What OpenAIProcessor.process_question returns.
Result = dict[str, Any]

# The earlier answers sent with a question: at most this many characters in
# all (about 7,500 tokens), the closest questions first; each answer cut past
# EARLIER_ANSWER_MAX_CHARS.
EARLIER_ANSWERS_MAX_CHARS = 30_000
EARLIER_ANSWER_MAX_CHARS = 3_000

EARLIER_ANSWERS_INTRO = (
    "Answers already written for the earlier questions of this due diligence, "
    "for context. Use them where they help with the question that follows (the "
    "same fund, team or figures). They are not sources: check every fact you take "
    "from them against the documents or the web, and cite those."
)

# Why a version of an answer was written, as its history records it and the
# versions panel shows it, in the interface's language.
INITIAL_ANSWER_REASON = "Initial AI-generated answer"


def regeneration_reason(instruction: str | None, *, guided: bool) -> str:
    """The history's reason for a regenerated answer: the analyst's instruction
    when there is one, kept for traceability. `guided`: a reference URL or an
    attached file was given."""
    if instruction:
        return "Regenerated by the AI — instruction: " + instruction[:200]
    if guided:
        return "Regenerated by the AI (guided)"
    return "Regenerated by the AI"


class QuestionFailed(Exception):
    """A question OpenAI could not answer, after the engine's retries. Raised
    from OpenAI's error; `message` is the one the user reads in a run."""

    def __init__(self, failure: Failure, retries: int, message: str) -> None:
        super().__init__(failure.type.value)
        self.failure = failure
        self.retries = retries
        self.message = message


def _sources(result: Result) -> dict[str, Any]:
    """The sources of a result, as stored: always a dict of files and web."""
    sources = result.get("sources")
    if isinstance(sources, dict):
        return sources
    if isinstance(sources, list):
        logger.warning("Sources came as a list: structured into a dict")
        return {
            "files": [s for s in sources if isinstance(s, dict) and s.get("type") == "file_search"],
            "web": [s for s in sources if isinstance(s, dict) and s.get("type") == "web_search"],
            "total_count": len(sources),
        }
    if sources is not None:
        logger.warning("Sources of an unexpected type (%s): dropped", type(sources).__name__)
    return {}


class DDProcessor:
    MAX_ATTEMPTS = 3  # OpenAI calls per question, retries included
    CIRCUIT_BREAKER_THRESHOLD = 1  # consecutive global failures that stop the run

    def __init__(self, execution_id: int, dd_type_id: int, dd_type_code: str) -> None:
        self.execution_id = execution_id
        self.dd_type_id = dd_type_id
        self.dd_type_code = dd_type_code
        self.openai_processor = OpenAIProcessor()
        self.rate_limiter = RateLimiter()
        self.consecutive_global_failures = 0

    @staticmethod
    def compose_question_text(question: Any) -> str:
        """The question as the model sees it: section heading + text + sources.

        Two things used to be dropped on the floor here. The section title never
        left the database, so a question arrived stripped of its theme. And
        ``context_prompt`` -- offered in the UI as "Context Prompt / Provide
        context or hints for answering..." -- was stored and displayed but never
        sent, so anyone filling it in was working for nothing.

        ``context_prompt`` now carries the "where to look" instruction of the
        reference questionnaires, moved out of the question text so it can be
        edited. It is labelled "Where to look" whatever its origin, which is what
        makes questionnaires speak the same language when their source workbooks
        name that column differently ("Document / evidence expected" against
        "Expected answer / evidence").
        """
        parts = []

        section = getattr(question, "section", None)
        if section is not None and section.title:
            heading = f"[Section: {section.title}]"
            # The section description is analyst-written context about the theme.
            # It is only sent when it says something: imports used to fill it with
            # "Section for <title>", which would repeat the title once per question.
            description = (getattr(section, "description", None) or "").strip()
            if description:
                heading = f"{heading}\n{description}"
            parts.append(heading)

        parts.append(question.question_text)

        sources = (getattr(question, "context_prompt", None) or "").strip()
        if sources:
            parts.append(f"Where to look: {sources}")

        return "\n\n".join(parts)

    @staticmethod
    def compose_earlier_answers(answers: Sequence[tuple[str, str, str]]) -> str | None:
        """The message of earlier answers sent before a question, or None.

        `answers` holds (code, question text, answer text) for the earlier
        questions, in the questionnaire's order. Within the budget, the closest
        questions win: they are the most likely to bear on the next one. What
        is kept is then written in the questionnaire's order.
        """
        kept: list[str] = []
        total = 0
        for code, question_text, answer_text in reversed(answers):
            text = answer_text.strip()
            if not text:
                continue
            if len(text) > EARLIER_ANSWER_MAX_CHARS:
                text = text[:EARLIER_ANSWER_MAX_CHARS].rstrip() + " […]"
            entry = f"[{code}] {question_text.strip()}\n{text}"
            if total + len(entry) > EARLIER_ANSWERS_MAX_CHARS:
                break
            kept.append(entry)
            total += len(entry)
        if not kept:
            return None
        return "\n\n".join([EARLIER_ANSWERS_INTRO, *reversed(kept)])

    # --- Runs ---------------------------------------------------------------------

    def start_processing(self, vector_store_ids: list[str], company_info: dict[str, Any]) -> bool:
        """Answer every question of the DD type."""
        return self._run(vector_store_ids, company_info, resume=False)

    def resume_processing(self, vector_store_ids: list[str], company_info: dict[str, Any]) -> bool:
        """Answer the questions not answered yet, or failed."""
        return self._run(vector_store_ids, company_info, resume=True)

    def _run(
        self, vector_store_ids: list[str], company_info: dict[str, Any], *, resume: bool
    ) -> bool:
        """The one loop of a run. False when it stopped on an error of its own
        (not one of a question): the run is then failed."""
        with database.SessionLocal() as db:
            try:
                questions = self._prepare(db, resume=resume)
                logger.info(
                    "Execution %s (%s): %s %s questions",
                    self.execution_id,
                    self.dd_type_code,
                    "resuming" if resume else "starting",
                    len(questions),
                )
                paused, failed = self._loop(db, questions, vector_store_ids, company_info)
                status = self._final_status(paused=paused, failed=failed)
                if status is not None:
                    self._set_status(db, status, only_if_running=True)
                logger.info(
                    "Execution %s ended: %s (%s of %s questions failed)",
                    self.execution_id,
                    status.value if status else "paused",
                    failed,
                    len(questions),
                )
                self._stop_clock(db)
                return True
            except Exception:
                logger.exception("Execution %s stopped on an error", self.execution_id)
                db.rollback()
                self._set_status(db, ExecutionStatus.FAILED, only_if_running=False)
                self._stop_clock(db)
                return False

    def _stop_clock(self, db: Session) -> None:
        """Add the stretch that just ended to the run's time. Not when the run
        is in progress again: a resume clicked before this loop saw the pause
        has started a stretch of its own."""
        execution = self._execution(db)
        if execution.status == ExecutionStatus.IN_PROGRESS or execution.running_since is None:
            return
        execution.run_seconds = execution.elapsed_seconds()
        execution.running_since = None
        db.commit()

    @staticmethod
    def _final_status(*, paused: bool, failed: int) -> ExecutionStatus | None:
        """The status a run ends with; None to leave it as it is (paused)."""
        if paused:
            return None
        return ExecutionStatus.FAILED if failed else ExecutionStatus.GENERATED

    def _prepare(self, db: Session, *, resume: bool) -> list[DDQuestion]:
        """The questions to answer. A start opens a new conversation; a resume
        keeps the run's, and only takes the questions without a good answer."""
        execution = self._execution(db)
        questions = self._questions(db)
        if resume:
            questions = self._still_to_answer(db, questions)
        if not resume or not execution.conversation_id:
            execution.conversation_id = str(uuid.uuid4())
        db.commit()
        return questions

    def _loop(
        self,
        db: Session,
        questions: Sequence[DDQuestion],
        vector_store_ids: list[str],
        company_info: dict[str, Any],
    ) -> tuple[bool, int]:
        """Answer the questions in turn. Returns whether the user paused the
        run, and how many questions failed."""
        failed = 0
        for done, question in enumerate(questions):
            if not self._still_running(db):
                logger.info(
                    "Execution %s paused after %s of %s questions",
                    self.execution_id,
                    done,
                    len(questions),
                )
                return True, failed
            if self.consecutive_global_failures >= self.CIRCUIT_BREAKER_THRESHOLD:
                logger.error(
                    "Execution %s: circuit breaker open after %s global failures, "
                    "%s questions left unasked",
                    self.execution_id,
                    self.consecutive_global_failures,
                    len(questions) - done,
                )
                return False, failed
            try:
                self._answer(db, question, vector_store_ids, company_info)
            except QuestionFailed as error:
                failed += 1
                if is_global(error.failure.type):
                    self.consecutive_global_failures += 1
                else:
                    self.consecutive_global_failures = 0
            except Exception:
                # Answered, but not stored: nothing was kept for this question.
                logger.exception("Execution %s: an answer could not be stored", self.execution_id)
                db.rollback()
                failed += 1
                self.consecutive_global_failures = 0
            else:
                self.consecutive_global_failures = 0
        return False, failed

    # --- One question -------------------------------------------------------------

    def _answer(
        self,
        db: Session,
        question: DDQuestion,
        vector_store_ids: list[str],
        company_info: dict[str, Any],
    ) -> None:
        """Ask one question, then store what came back, in one transaction."""
        question_id = stored_id(question)
        question_text = self.compose_question_text(question)
        earlier_answers = self._earlier_answers(db, question)
        db.commit()  # ends the read: no transaction stays open during the call

        try:
            result, retries = self._call(
                lambda: self.openai_processor.process_question(
                    question_text=question_text,
                    vector_store_ids=vector_store_ids,
                    earlier_answers=earlier_answers,
                    company_info=company_info,
                )
            )
        except QuestionFailed as error:
            self._store_failure(db, question_id, error)
            raise
        self._store_answer(db, question_id, result, retries)
        self.rate_limiter.check_and_sleep_sync(tokens_used=result["tokens_used"])

    def _call(self, call: Callable[[], Result]) -> tuple[Result, int]:
        """Call OpenAI, trying again what may pass on a second try, up to
        MAX_ATTEMPTS calls. Returns the result and the number of retries."""
        attempt = 0
        while True:
            try:
                return call(), attempt
            except Exception as error:
                failure = classify(error)
                if not failure.retryable or attempt + 1 >= self.MAX_ATTEMPTS:
                    logger.exception(
                        "Execution %s: OpenAI call failed (%s), call %s of %s, given up",
                        self.execution_id,
                        failure.type.value,
                        attempt + 1,
                        self.MAX_ATTEMPTS,
                    )
                    raise QuestionFailed(
                        failure, attempt, question_message(error, failure)
                    ) from error
                delay = retry_delay(error, failure, attempt)
                logger.warning(
                    "Execution %s: OpenAI call failed (%s: %s), again in %.1fs",
                    self.execution_id,
                    failure.type.value,
                    error,
                    delay,
                )
                time.sleep(delay)
                attempt += 1

    def _store_answer(self, db: Session, question_id: int, result: Result, retries: int) -> None:
        """One transaction: the raw response and its messages, the old answer
        set aside, the new answer and the first version of its history."""
        try:
            execution = self._execution(db)
            question = self._question(db, question_id)
            response = self._add_response(db, execution, result)
            self._set_aside_current(db, execution, question)
            sources = _sources(result)
            answer = new_answer(
                execution,
                question,
                answer_text=result["answer"],
                sources=sources,
                tokens_used=result["tokens_used"],
                # OpenAI's raw response, kept in dd_responses.
                response_id=response.response_id,
                status=AnswerStatus.COMPLETED,
                retry_count=retries,
            )
            db.add(answer)
            db.flush()
            db.add(
                DDAnswerHistory(
                    answer_id=stored_id(answer),
                    version=1,
                    content=result["answer"],
                    sources=sources,
                    edited_by=None,  # NULL: written by the AI
                    edit_reason=INITIAL_ANSWER_REASON,
                )
            )
            db.commit()
        except Exception:
            db.rollback()
            raise

    def _store_failure(self, db: Session, question_id: int, error: QuestionFailed) -> None:
        """One transaction: the old answer set aside, a failed answer in its
        place. Its message is written for the user, never OpenAI's text."""
        try:
            execution = self._execution(db)
            question = self._question(db, question_id)
            self._set_aside_current(db, execution, question)
            db.add(
                new_answer(
                    execution,
                    question,
                    status=AnswerStatus.FAILED,
                    retry_count=error.retries,
                    error_type=error.failure.type,
                    error_message=error.message,
                    last_error_at=datetime.now(UTC),
                )
            )
            db.commit()
        except Exception:
            db.rollback()
            raise

    @staticmethod
    def _add_response(db: Session, execution: DDExecution, result: Result) -> DDResponse:
        """The raw OpenAI response and its messages (flushed, not committed)."""
        response = DDResponse(
            execution_id=stored_id(execution),
            response_id=result["response_id"],
            openai_response=result.get("full_response", {}),
        )
        db.add(response)
        db.flush()
        messages = result.get("messages") or []
        for index, message in enumerate(messages):
            if message is None:
                continue
            db.add(
                DDMessage(
                    response_id=response.response_id,
                    message_index=index,
                    role=message.get("role", "unknown"),
                    content=message.get("content"),
                    tool_calls=message.get("tool_calls"),
                    openai_message_id=message.get("id"),
                )
            )
        db.flush()
        return response

    @staticmethod
    def _set_aside_current(db: Session, execution: DDExecution, question: DDQuestion) -> None:
        """The question's current answer is no longer current (it stays in the table)."""
        db.execute(
            update(DDAnswer)
            .where(
                col(DDAnswer.execution_id) == execution.id,
                col(DDAnswer.question_id) == question.id,
                col(DDAnswer.is_current).is_(True),
            )
            .values(is_current=False)
            .execution_options(synchronize_session=False)
        )

    # --- Reading ------------------------------------------------------------------

    def _execution(self, db: Session) -> DDExecution:
        execution = db.get(DDExecution, self.execution_id)
        if execution is None:
            raise ValueError(f"Execution {self.execution_id} not found")
        return execution

    @staticmethod
    def _question(db: Session, question_id: int) -> DDQuestion:
        question = db.get(DDQuestion, question_id)
        if question is None:
            raise ValueError(f"Question {question_id} not found")
        return question

    def _questions(self, db: Session) -> list[DDQuestion]:
        """Every question of the DD type, in the questionnaire's order."""
        questions = list(
            db.scalars(
                select(DDQuestion)
                .join(DDSection, col(DDQuestion.section_id) == col(DDSection.id))
                .where(col(DDSection.dd_type_id) == self.dd_type_id)
                .order_by(
                    col(DDSection.order_index),
                    col(DDQuestion.order_index),
                    col(DDSection.id),
                    col(DDQuestion.id),
                )
            )
        )
        if not questions:
            raise ValueError(f"No questions found for DD type {self.dd_type_code}")
        return questions

    def _still_to_answer(self, db: Session, questions: list[DDQuestion]) -> list[DDQuestion]:
        """The questions whose current answer is missing or failed."""
        answered = set(
            db.scalars(
                select(col(DDAnswer.question_id)).where(
                    col(DDAnswer.execution_id) == self.execution_id,
                    col(DDAnswer.is_current).is_(True),
                    col(DDAnswer.status) != AnswerStatus.FAILED,
                )
            )
        )
        return [question for question in questions if question.id not in answered]

    @staticmethod
    def _place(section: DDSection, question: DDQuestion) -> tuple[int, int, int, int]:
        """Where a question stands in the questionnaire, as _questions orders it.
        `order_index` alone starts again at 0 in every section."""
        return (section.order_index, question.order_index, stored_id(section), stored_id(question))

    def _earlier_answers(self, db: Session, question: DDQuestion) -> str | None:
        """The current answers of the run's earlier questions, as the message
        sent before this one (compose_earlier_answers). Failed and rejected
        answers are left out."""
        section = question.section
        if section is None:
            return None
        here = self._place(section, question)
        rows = db.execute(
            select(DDAnswer, DDQuestion, DDSection)
            .join(DDQuestion, col(DDAnswer.question_id) == col(DDQuestion.id))
            .join(DDSection, col(DDQuestion.section_id) == col(DDSection.id))
            .where(
                col(DDAnswer.execution_id) == self.execution_id,
                col(DDAnswer.is_current).is_(True),
                col(DDAnswer.status).not_in([AnswerStatus.FAILED, AnswerStatus.REJECTED]),
                col(DDAnswer.answer_text).isnot(None),
            )
        ).all()
        earlier = sorted(
            (self._place(s, q), a.question_code, q.question_text, a.answer_text or "")
            for a, q, s in rows
            if self._place(s, q) < here
        )
        return self.compose_earlier_answers([(code, q, a) for _, code, q, a in earlier])

    def _still_running(self, db: Session) -> bool:
        """Whether the run is still in progress: a pause sets it to `paused`,
        which the loop sees before the next question."""
        status = db.scalar(
            select(col(DDExecution.status)).where(col(DDExecution.id) == self.execution_id)
        )
        db.commit()
        return status == ExecutionStatus.IN_PROGRESS

    def _set_status(self, db: Session, status: ExecutionStatus, *, only_if_running: bool) -> None:
        """Set the run's status. At the end of a run, only if it is still in
        progress: a pause that arrived after the last question stays."""
        query = update(DDExecution).where(col(DDExecution.id) == self.execution_id)
        if only_if_running:
            query = query.where(col(DDExecution.status) == ExecutionStatus.IN_PROGRESS)
        db.execute(query.values(status=status).execution_options(synchronize_session=False))
        db.commit()

    # --- Regeneration -------------------------------------------------------------

    def regenerate_single_answer(
        self,
        db: Session,
        answer: DDAnswer,
        vector_store_ids: list[str],
        company_info: dict[str, Any],
        instruction: str | None = None,
        reference_url: str | None = None,
        extra_file_source: dict[str, Any] | None = None,
    ) -> DDAnswer:
        """Regenerate ONE existing answer on demand (interactive).

        Sends the earlier answers for context, like a question of a run, but
        skips the batch rate-limiter and circuit breaker since this is a single,
        user-triggered call. Updates the answer in place as a new version
        (mirrors the manual-edit pattern), so the version history and the
        'revert to version' feature keep working. Status -> NEEDS_REVIEW.

        Optional guidance: ``instruction`` (analyst re-prompt) and
        ``reference_url`` are appended to the question; ``extra_file_source``
        (a file uploaded by the caller to a session vector store) is merged into
        the answer's sources. When any guidance is present, the call uses
        ``tool_choice="auto"`` so file_search (attached doc) and web_search
        (reference URL) are both usable instead of the default forced web search.

        Like a question of a run: the call outside any transaction, then one
        transaction for all it writes.
        """
        question = answer.question
        if question is None or question.section is None:
            raise ValueError("Answer has no associated question/section")
        answer_id = stored_id(answer)
        earlier_answers = self._earlier_answers(db, question)

        # The (optionally guided) question text.
        guided = bool(instruction or reference_url or extra_file_source)
        extras = []
        if instruction:
            extras.append("Additional instruction from the analyst: " + instruction)
        if reference_url:
            extras.append("Web source to check first: " + reference_url)
        question_text = self.compose_question_text(question) + (
            ("\n\n" + "\n".join(extras)) if extras else ""
        )

        # Use 'auto' whenever there are documents to reuse (the session vector
        # store(s) that served this answer) or explicit guidance, so file_search
        # actually queries them instead of being shadowed by the forced web
        # search. Only fall back to the default (forced web) when there is
        # nothing to reuse and no guidance.
        tool_choice = "auto" if (guided or vector_store_ids) else None
        db.commit()  # ends the read: no transaction stays open during the call

        try:
            result, _retries = self._call(
                lambda: self.openai_processor.process_question(
                    question_text=question_text,
                    vector_store_ids=vector_store_ids,
                    earlier_answers=earlier_answers,
                    company_info=company_info,
                    tool_choice=tool_choice,
                )
            )
        except QuestionFailed as error:
            # Not a run: no Resume to point to (engine/errors.operation_message).
            raise ExternalServiceError(operation_message(error.__cause__ or error)) from error

        sources = _sources(result)
        # Inject the analyst-attached file into the sources (so it shows up in
        # the UI and the PDF), unless the model already cited it via file_search.
        if extra_file_source and extra_file_source.get("file_id"):
            files_list = sources.get("files")
            if not isinstance(files_list, list):
                files_list = []
            already = any(
                isinstance(s, dict) and s.get("file_id") == extra_file_source["file_id"]
                for s in files_list
            )
            if not already:
                files_list.append(extra_file_source)
                sources["files"] = files_list
                sources["total_count"] = sources.get("total_count", 0) + 1

        edit_reason = regeneration_reason(
            instruction, guided=bool(reference_url or extra_file_source)
        )

        try:
            stored = db.get(DDAnswer, answer_id)
            if stored is None:
                raise ValueError(f"Answer {answer_id} not found")
            response = self._add_response(db, self._execution(db), result)
            new_version = stored.version + 1
            db.add(
                DDAnswerHistory(
                    answer_id=answer_id,
                    version=new_version,
                    content=result["answer"],
                    sources=sources,
                    edited_by=None,  # NULL = AI-generated
                    edit_reason=edit_reason,
                )
            )
            stored.version = new_version
            stored.answer_text = result["answer"]
            stored.sources = sources
            stored.tokens_used = result.get("tokens_used") or 0
            stored.response_id = response.response_id
            stored.status = AnswerStatus.NEEDS_REVIEW
            stored.edited_by = None
            stored.edited_at = datetime.now(UTC)
            stored.is_current = True
            db.commit()
        except Exception:
            db.rollback()
            raise
        db.refresh(stored)
        logger.info("Regenerated answer %s (new version %s)", answer_id, new_version)
        return stored
